#!/usr/bin/env bash
# Repeatable tiles/SDL2 release build of this tree.
# Does not install the game, does not read or write save directories,
# and does not pass USE_HOME_DIR (that would put config and saves in $HOME).
# Same license as the rest of this repository (CC BY-SA 3.0).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

EXPECTED="7b2efa5cea38e4d4d97dd0e63b28b9148623da59"
if ! git rev-parse --verify "${EXPECTED}^{commit}" >/dev/null 2>&1; then
  echo "Missing upstream 0.I-1 commit ${EXPECTED}." >&2
  echo "Fetch it with: git fetch https://github.com/CleverRaven/Cataclysm-DDA.git tag 0.I-1" >&2
  exit 1
fi
if ! git merge-base --is-ancestor "$EXPECTED" HEAD; then
  echo "HEAD $(git rev-parse --short HEAD) does not contain 0.I-1 ${EXPECTED}." >&2
  exit 1
fi

JOBS="${JOBS:-$(nproc)}"
LOG="${CDDA_BUILD_LOG:-/tmp/cdda-build-logs/tiles-release.log}"
mkdir -p "$(dirname "$LOG")"

{
  echo "START $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "HEAD $(git rev-parse HEAD)"
  echo "0.I-1 ${EXPECTED}"
  echo "make -j${JOBS} TILES=1 SOUND=1 RELEASE=1 LOCALIZE=0 LTO=0 CCACHE=1"
} | tee "$LOG"

# LOCALIZE=0 keeps the build English-only and skips gettext compilation.
# LTO is left off: link-time optimization is slow and memory-heavy on a small VM.
# Extra make arguments may be passed through, for example: JOBS=2 ./tools/vm-baseline/build-tiles.sh
make -j"$JOBS" TILES=1 SOUND=1 RELEASE=1 LOCALIZE=0 LTO=0 CCACHE=1 "$@" 2>&1 | tee -a "$LOG"
status="${PIPESTATUS[0]}"
{
  echo "EXIT ${status} $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  if [[ -x "$ROOT/cataclysm-tiles" ]]; then
    echo "BINARY $ROOT/cataclysm-tiles"
    ls -lh "$ROOT/cataclysm-tiles"
    # version.h is generated by the Makefile and is gitignored.
    if [[ -f "$ROOT/src/version.h" ]]; then
      echo "VERSION_H:"
      cat "$ROOT/src/version.h"
    fi
  fi
} | tee -a "$LOG"
exit "$status"
